import * as fs from 'node:fs';
import * as path from 'node:path';
import * as cdk from 'aws-cdk-lib';
import { Construct } from 'constructs';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as kms from 'aws-cdk-lib/aws-kms';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import * as logs from 'aws-cdk-lib/aws-logs';
import * as secretsmanager from 'aws-cdk-lib/aws-secretsmanager';
import * as ssm from 'aws-cdk-lib/aws-ssm';

export const BUILD_DIR = path.join(__dirname, '..', '..', 'build');
export const READERS = ['cached-reader', 'extension-reader'] as const;
export type ReaderName = (typeof READERS)[number];

/** Parameter Store names. CloudFormation can't create a SecureString, so scripts/put-parameter.ts does. */
export const PARAMETER_NAME = '/secrets-cost-choice/db-password';

/**
 * AWS publishes the newest extension layer ARN as a public parameter. CloudFormation reads
 * it at deploy time. CDK's built-in ParamsAndSecretsVersions.V1_0_103 still points at layer
 * version 4 for arm64 in us-east-1, while the AWS docs list version 116 (checked 2026-10-15).
 */
export const EXTENSION_LAYER_PARAMETER = '/aws/service/aws-parameters-and-secrets-lambda-extension/arm64/latest';

export interface SecretsStackProps extends cdk.StackProps {
  /** Seconds a reader may reuse a value. Both caches cap at 300 here. */
  cacheTtlSeconds?: number;
}

export class SecretsStack extends cdk.Stack {
  constructor(scope: Construct, id: string, props: SecretsStackProps = {}) {
    super(scope, id, props);

    const ttl = props.cacheTtlSeconds ?? 300;
    if (!Number.isInteger(ttl) || ttl < 0 || ttl > 300) {
      throw new Error(`cacheTtlSeconds must be 0-300 (the extension's maximum), got ${ttl}`);
    }
    for (const name of READERS) {
      if (!fs.existsSync(path.join(BUILD_DIR, name, 'index.js'))) {
        throw new Error(`build/${name}/index.js is missing. Run "npm run bundle" first.`);
      }
    }

    // One customer managed key for both stores. It costs a monthly fee that the AWS managed
    // keys (aws/ssm, aws/secretsmanager) don't, and it buys two things: a key policy you
    // control, and the option to share the secret with another account later.
    const key = new kms.Key(this, 'SecretsKey', {
      alias: 'alias/secrets-cost-choice',
      description: 'Encrypts the demo secret and SecureString parameter',
      enableKeyRotation: true,
      pendingWindow: cdk.Duration.days(7),
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });

    // Secrets Manager generates the value at deploy time, so it never appears in the template.
    const secret = new secretsmanager.Secret(this, 'PartnerApiKey', {
      secretName: 'secrets-cost-choice/partner-api-key',
      description: 'Demo API key, generated by Secrets Manager',
      encryptionKey: key,
      generateSecretString: { excludePunctuation: true, passwordLength: 40 },
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });
    cdk.Validations.of(secret).acknowledge({
      id: 'AwsSolutions::AwsSolutions-SMG4',
      reason:
        'Stands in for a third-party API key, which only the issuer can rotate, so there is no rotation function to attach. ' +
        'docs/runbook.md has the manual rotation steps.',
    });

    const parameterArn = this.formatArn({
      service: 'ssm',
      resource: 'parameter',
      resourceName: PARAMETER_NAME.slice(1),
    });

    const extensionLayerArn = ssm.StringParameter.valueForStringParameter(this, EXTENSION_LAYER_PARAMETER);

    const readers = Object.fromEntries(
      READERS.map((name) => [
        name,
        this.reader(name, {
          secret,
          key,
          parameterArn,
          ttl,
          extensionLayerArn,
        }),
      ]),
    ) as Record<ReaderName, lambda.Function>;

    new cdk.CfnOutput(this, 'CachedReaderName', { value: readers['cached-reader'].functionName });
    new cdk.CfnOutput(this, 'ExtensionReaderName', { value: readers['extension-reader'].functionName });
    new cdk.CfnOutput(this, 'SecretArn', { value: secret.secretArn });
    new cdk.CfnOutput(this, 'ParameterName', { value: PARAMETER_NAME });
    new cdk.CfnOutput(this, 'KeyArn', { value: key.keyArn });
  }

  private reader(
    name: ReaderName,
    deps: { secret: secretsmanager.ISecret; key: kms.IKey; parameterArn: string; ttl: number; extensionLayerArn: string },
  ): lambda.Function {
    const logGroup = new logs.LogGroup(this, `${name}-logs`, {
      retention: logs.RetentionDays.TWO_WEEKS,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });

    // A role per function with exactly the reads it needs. No managed policies.
    const role = new iam.Role(this, `${name}-role`, {
      assumedBy: new iam.ServicePrincipal('lambda.amazonaws.com'),
      description: `${name}: read one secret and one parameter`,
    });
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'WriteOwnLogs',
        actions: ['logs:CreateLogStream', 'logs:PutLogEvents'],
        resources: [logGroup.logGroupArn],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'ReadTheSecret',
        actions: ['secretsmanager:GetSecretValue'],
        resources: [deps.secret.secretArn],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'ReadTheParameter',
        actions: ['ssm:GetParameter'],
        resources: [deps.parameterArn],
      }),
    );
    // kms:Decrypt on the key, but only when Secrets Manager asks for this one secret...
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'DecryptViaSecretsManager',
        actions: ['kms:Decrypt'],
        resources: [deps.key.keyArn],
        conditions: {
          StringEquals: {
            'kms:ViaService': `secretsmanager.${this.region}.amazonaws.com`,
            'kms:EncryptionContext:SecretARN': deps.secret.secretArn,
          },
        },
      }),
    );
    // ...or when Parameter Store asks for this one parameter.
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'DecryptViaParameterStore',
        actions: ['kms:Decrypt'],
        resources: [deps.key.keyArn],
        conditions: {
          StringEquals: {
            'kms:ViaService': `ssm.${this.region}.amazonaws.com`,
            'kms:EncryptionContext:PARAMETER_ARN': deps.parameterArn,
          },
        },
      }),
    );

    const fn = new lambda.Function(this, name, {
      description: `Reads the demo secret and parameter (${name})`,
      runtime: lambda.Runtime.NODEJS_24_X,
      architecture: lambda.Architecture.ARM_64,
      handler: 'index.handler',
      code: lambda.Code.fromAsset(path.join(BUILD_DIR, name)),
      memorySize: 256,
      timeout: cdk.Duration.seconds(10),
      role,
      logGroup,
      environment: {
        SECRET_ID: deps.secret.secretArn,
        PARAMETER_NAME: PARAMETER_NAME,
        ...(name === 'cached-reader' ? { CACHE_TTL_SECONDS: String(deps.ttl) } : {}),
      },
      ...(name === 'extension-reader'
        ? {
            paramsAndSecrets: lambda.ParamsAndSecretsLayerVersion.fromVersionArn(deps.extensionLayerArn, {
              cacheSize: 100,
              secretsManagerTtl: cdk.Duration.seconds(deps.ttl),
              parameterStoreTtl: cdk.Duration.seconds(deps.ttl),
              // The default, 0, means the extension waits forever on a slow API call.
              secretsManagerTimeout: cdk.Duration.seconds(2),
              parameterStoreTimeout: cdk.Duration.seconds(2),
              logLevel: lambda.ParamsAndSecretsLogLevel.WARN,
            }),
          }
        : {}),
    });
    return fn;
  }
}
